def lookup_source_catalog(source_name: str) -> SourceCatalogEntry | None:
    return SOURCE_CATALOG.get(normalize_source_name(source_name))


def catalog_summary() -> dict[str, int]:
    return {
        "sources": len(SOURCE_CATALOG),
        "agent_sources": sum(1 for item in SOURCE_CATALOG.values() if item.segment == "AGENT"),
        "direct_sources": sum(1 for item in SOURCE_CATALOG.values() if item.segment == "DIRECT"),
        "country_default_sources": sum(
            1 for item in SOURCE_CATALOG.values() if item.default_country_code
        ),
        "scope_only_sources": sum(
            1 for item in SOURCE_CATALOG.values() if not item.default_country_code
        ),
    }
